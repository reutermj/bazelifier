#!/usr/bin/env python3
"""Unit tests for tools/catalog/harvest.py.

    python3 tools/catalog/harvest_test.py

The inputs are configure fragments in both autoconf dialects the corpus
carries (2.69: ac_fn_c_check_decl, `do :` on its own line; 2.71:
ac_fn_check_decl with two trailing arguments), so the test can fail on the
spelling difference that would otherwise drop every declaration of one
dialect. Host compiles are replaced by a fake that answers from a table, so
the header choice and the absent/present verdicts are pinned without a
compiler.
"""
